"""Build masssigray/data/i0_reference.csv from raw spectrometer exports.

    python scripts/build_i0_reference.py source/*.csv

Each export becomes one window named after its file (Cu.csv -> "Cu"). The I0
signal is the sum of the reference pixel columns (Algn R 1 ... Algn R n), in ADU
per point. A smoothed curve over the full span of the windows is written to
i0_smooth.csv. Exports whose signal duplicates another file are reported.
"""
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from masssigray.flux import (INSTRUMENT_FILE, SMOOTH_FILE, read_reference_scan,  # noqa: E402
                             smooth_windows)


def main(paths):
    windows = {}
    for p in map(Path, paths):
        windows[p.stem] = read_reference_scan(p)
    names = sorted(windows, key=lambda k: windows[k][0][0])

    for i, a in enumerate(names):
        for b in names[i + 1:]:
            sa, sb = windows[a][1], windows[b][1]
            if sa.size == sb.size and np.allclose(sa, sb):
                print(f"WARNING: {b} has the same reference signal as {a} (only energies differ)")

    INSTRUMENT_FILE.parent.mkdir(exist_ok=True)
    with open(INSTRUMENT_FILE, "w", encoding="utf-8") as fh:
        fh.write("# Lab spectrometer I0: summed reference pixels (ADU per point) per measured window.\n")
        fh.write("# Generated by scripts/build_i0_reference.py; do not edit by hand.\n")
        fh.write("window,energy_eV,reference_adu\n")
        for k in names:
            E, s = windows[k]
            for e, v in zip(E, s):
                fh.write(f"{k},{e:.3f},{v:.2f}\n")
            print(f"{k:3s} {E[0]:8.1f} - {E[-1]:8.1f} eV  {E.size:4d} points")
    print(f"wrote {INSTRUMENT_FILE}")

    grid, sm = smooth_windows({k: windows[k] for k in names})
    with open(SMOOTH_FILE, "w", encoding="utf-8") as fh:
        fh.write("# Lab spectrometer I0, smoothed over the full span of the measured windows (ADU per point).\n")
        fh.write("# Generated by scripts/build_i0_reference.py; do not edit by hand.\n")
        fh.write("energy_eV,reference_adu\n")
        for e, v in zip(grid, sm):
            fh.write(f"{e:.1f},{v:.1f}\n")
    print(f"wrote {SMOOTH_FILE} ({grid[0]:.0f}-{grid[-1]:.0f} eV, {grid.size} points)")


if __name__ == "__main__":
    main(sys.argv[1:])
